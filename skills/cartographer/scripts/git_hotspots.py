#!/usr/bin/env python3
"""
Phase 1.2: rank git hot spots and temporal coupling.

Reads `git log` over a time window and computes, per file, how often it changed, how many lines it churned and
how many people changed it. A hot spot is a file that changes often and is complex: score = commits x indentation
complexity, the language-neutral complexity proxy from Adam Tornhill's "Your Code as a Crime Scene". Temporal
coupling lists file pairs that keep changing in the same commits, and says whether an import links them.

Approach from Matt Pocock's improve-codebase-architecture skill (MIT, https://github.com/mattpocock/skills).

Writes hotspots.json and hotspots.md next to project-map.json and adds a `hotspots` summary to project-map.json.
A folder that is not a git repo, or has no commits in the window, still gets both files with the reason.
"""
from __future__ import annotations

import argparse
import json
import re
import subprocess
import sys
from collections import Counter, defaultdict
from datetime import datetime, timezone
from itertools import combinations
from pathlib import Path

GIT_TIMEOUT_SECONDS = 300
# Bulk commits (formatting runs, renames, dependency bumps) touch many files at once and would couple
# everything with everything; code-maat drops changesets above a similar size for the same reason.
MAX_FILES_PER_COMMIT_FOR_COUPLING = 30
# Below 5 shared commits a pair is noise on a repo with a few hundred commits a year.
MIN_SHARED_COMMITS = 5
# Pairs that change together in at least half of their commits (shared / mean of both commit counts).
MIN_COUPLING_DEGREE = 0.5
TOP_HOTSPOTS = 30
TOP_COUPLING = 40
# Files that are data or prose rather than code; they still get change counts but stay out of the ranking.
NON_CODE_LANGS = {"lockfile", "markdown", "text", "json", "yaml", "csv", "svg", "rst", "asciidoc", "toml",
                  "ini", "xml", "dotfile", "codeowners", "other"}
TAB_WIDTH = 4
# Generated code (OpenAPI clients, protobuf stubs) churns on every regeneration and would top the ranking;
# generators mark it in the header, so only the first 2 KB are checked.
GENERATED_HEADER_RE = re.compile(r"auto[- ]?generated|@generated|do not edit|generated by", re.I)
GENERATED_HEADER_BYTES = 2048


def git(root: Path, *args: str) -> subprocess.CompletedProcess:
    return subprocess.run(["git", "-C", str(root), *args], capture_output=True, text=True,
                          timeout=GIT_TIMEOUT_SECONDS, errors="replace")


def indentation_complexity(path: Path) -> tuple[int, bool]:
    """Sum of indentation levels over non-blank lines (the indent unit is the smallest indent in the file),
    and whether the header marks the file as generated."""
    try:
        text = path.read_text(encoding="utf-8", errors="replace")
    except OSError:
        return 0, False
    generated = bool(GENERATED_HEADER_RE.search(text[:GENERATED_HEADER_BYTES]))
    lines = text.splitlines()
    widths = []
    for line in lines:
        stripped = line.lstrip(" \t")
        if not stripped:
            continue
        lead = line[: len(line) - len(stripped)]
        widths.append(lead.count(" ") + lead.count("\t") * TAB_WIDTH)
    unit = min((w for w in widths if w > 0), default=0)
    if not unit:
        return 0, generated
    return sum(w // unit for w in widths), generated


def read_log(root: Path, months: int) -> tuple[list[dict], str]:
    """Parse `git log --numstat` into commits. Paths are relative to `root` and limited to it."""
    proc = git(root, "log", f"--since={months} months ago", "--no-merges", "--no-renames", "--relative",
               "--numstat", "--format=%x1e%H%x1f%an%x1f%at", "--", ".")
    if proc.returncode != 0:
        return [], proc.stderr.strip()
    commits = []
    for chunk in proc.stdout.split("\x1e"):
        chunk = chunk.strip("\n")
        if not chunk:
            continue
        header, _, body = chunk.partition("\n")
        parts = header.split("\x1f")
        if len(parts) != 3:
            continue
        sha, author, ts = parts
        files = []
        for line in body.splitlines():
            cols = line.split("\t")
            if len(cols) != 3:
                continue
            added, deleted, path = cols
            churn = (int(added) if added.isdigit() else 0) + (int(deleted) if deleted.isdigit() else 0)
            files.append((path, churn))
        commits.append({"sha": sha, "author": author, "ts": int(ts), "files": files})
    return commits, ""


def compute(root: Path, pmap: dict, months: int) -> dict:
    result = {"available": False, "window_months": months, "reason": "", "shallow": False,
              "commits_scanned": 0, "files": [], "hotspots": [], "coupling": []}
    try:
        inside = git(root, "rev-parse", "--is-inside-work-tree")
    except (OSError, subprocess.TimeoutExpired) as exc:
        result["reason"] = f"git could not run: {exc}"
        return result
    if inside.returncode != 0 or inside.stdout.strip() != "true":
        result["reason"] = "not a git repository"
        return result
    result["shallow"] = git(root, "rev-parse", "--is-shallow-repository").stdout.strip() == "true"
    try:
        commits, err = read_log(root, months)
    except subprocess.TimeoutExpired:
        result["reason"] = f"git log took over {GIT_TIMEOUT_SECONDS}s"
        return result
    if err:
        result["reason"] = f"git log failed: {err}"
        return result
    if not commits:
        result["reason"] = f"no commits in the last {months} months"
        return result

    inventory = {e["path"]: e for e in pmap.get("inventory", [])}
    if not inventory:  # project-map.json from before the inventory existed
        inventory = {f["path"]: {"path": f["path"], "lang": f["lang"], "loc": f["loc"]} for f in pmap["files"]}
    edges = {tuple(sorted(e)) for e in pmap.get("edges", [])}

    revs, churn, authors, last = Counter(), Counter(), defaultdict(set), {}
    shared = Counter()
    for c in commits:
        paths = sorted({p for p, _ in c["files"] if p in inventory})
        for p, n in c["files"]:
            if p in inventory:
                churn[p] += n
        for p in paths:
            revs[p] += 1
            authors[p].add(c["author"])
            last[p] = max(last.get(p, 0), c["ts"])
        # A lockfile always moves with its manifest, which says nothing about the design.
        coupled = [p for p in paths if inventory[p].get("lang") != "lockfile"]
        if 2 <= len(coupled) and len(paths) <= MAX_FILES_PER_COMMIT_FOR_COUPLING:
            for a, b in combinations(coupled, 2):
                shared[(a, b)] += 1

    files = []
    for path, n in revs.items():
        entry = inventory[path]
        complexity, generated = indentation_complexity(root / path)
        files.append({
            "path": path, "lang": entry.get("lang", ""), "commits": n, "authors": len(authors[path]),
            "churn": churn[path], "loc": entry.get("loc", 0), "complexity": complexity,
            "score": n * complexity, "generated": generated,
            "last_change": datetime.fromtimestamp(last[path], tz=timezone.utc).date().isoformat(),
        })
    files.sort(key=lambda f: (-f["commits"], f["path"]))

    ranked = [f for f in files if f["lang"] not in NON_CODE_LANGS and f["score"] > 0 and not f["generated"]]
    ranked.sort(key=lambda f: (-f["score"], f["path"]))

    coupling = []
    for (a, b), n in shared.items():
        if n < MIN_SHARED_COMMITS:
            continue
        degree = n / ((revs[a] + revs[b]) / 2)
        if degree < MIN_COUPLING_DEGREE:
            continue
        coupling.append({"a": a, "b": b, "shared_commits": n, "degree": round(degree, 2),
                         "import_link": (a, b) in edges})
    coupling.sort(key=lambda c: (-c["shared_commits"], -c["degree"], c["a"]))

    result.update({
        "available": True, "commits_scanned": len(commits),
        "since": datetime.fromtimestamp(min(c["ts"] for c in commits), tz=timezone.utc).date().isoformat(),
        "files": files, "hotspots": ranked[:TOP_HOTSPOTS], "coupling": coupling[:TOP_COUPLING],
    })
    return result


def render_markdown(h: dict) -> str:
    lines = ["# Git hot spots", ""]
    if not h["available"]:
        lines += [f"No hot spots: {h['reason']}.", ""]
        return "\n".join(lines)
    lines.append(f"{h['commits_scanned']} commits since {h['since']} (window {h['window_months']} months, "
                 f"merges excluded). Score = commits x indentation complexity. Generated files "
                 f"({sum(1 for f in h['files'] if f.get('generated'))} with a generated-code header) are left out.")
    if h["shallow"]:
        lines.append("")
        lines.append("This is a shallow clone, so older history is missing and counts are low. "
                     "Run `git fetch --unshallow` for full numbers.")
    lines += ["", "## Hot spots", "",
              "| # | File | Commits | Authors | Churn | LOC | Complexity | Score | Last change |",
              "|---|------|---------|---------|-------|-----|------------|-------|-------------|"]
    for i, f in enumerate(h["hotspots"], 1):
        lines.append(f"| {i} | `{f['path']}` | {f['commits']} | {f['authors']} | {f['churn']} | {f['loc']} | "
                     f"{f['complexity']} | {f['score']} | {f['last_change']} |")
    lines += ["", "## Temporal coupling", ""]
    if not h["coupling"]:
        lines.append(f"No file pairs shared {MIN_SHARED_COMMITS}+ commits at degree "
                     f"{MIN_COUPLING_DEGREE}+.")
    else:
        lines.append("Pairs that change in the same commits. `no` under Import means nothing in the import "
                     "graph explains the link, which usually points to duplicated logic or a hidden contract.")
        lines += ["", "| File A | File B | Shared commits | Degree | Import |",
                  "|--------|--------|----------------|--------|--------|"]
        for c in h["coupling"]:
            lines.append(f"| `{c['a']}` | `{c['b']}` | {c['shared_commits']} | {c['degree']} | "
                         f"{'yes' if c['import_link'] else 'no'} |")
    lines.append("")
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("project_map", help="Path to project-map.json")
    ap.add_argument("--output-dir", "-o", help="Where to write hotspots.json/.md (default: next to the map)")
    ap.add_argument("--months", type=int, default=12, help="History window in months (default 12)")
    args = ap.parse_args()

    map_path = Path(args.project_map)
    if not map_path.is_file():
        sys.exit(f"project map not found: {map_path}. Run map_project.py first.")
    pmap = json.loads(map_path.read_text())
    root = Path(pmap["root"])
    out = Path(args.output_dir) if args.output_dir else map_path.parent
    out.mkdir(parents=True, exist_ok=True)

    h = compute(root, pmap, args.months)
    (out / "hotspots.json").write_text(json.dumps(h, indent=2))
    (out / "hotspots.md").write_text(render_markdown(h))

    pmap["hotspots"] = {k: h[k] for k in ("available", "reason", "window_months", "shallow", "commits_scanned",
                                          "hotspots", "coupling")}
    map_path.write_text(json.dumps(pmap, indent=2))

    if not h["available"]:
        print(f"Hot spots skipped: {h['reason']}. Wrote {out / 'hotspots.md'}", file=sys.stderr)
        return
    print(f"Wrote {out / 'hotspots.json'} and {out / 'hotspots.md'}", file=sys.stderr)
    print(f"{h['commits_scanned']} commits, {len(h['files'])} files changed, "
          f"{len(h['coupling'])} coupled pairs" + (" (shallow clone)" if h["shallow"] else ""), file=sys.stderr)
    for f in h["hotspots"][:5]:
        print(f"  {f['score']:>8}  {f['commits']:>4} commits  {f['path']}", file=sys.stderr)


if __name__ == "__main__":
    main()
